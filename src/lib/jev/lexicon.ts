const INDEX = new Map<string, string[]>();
for (const set of SYNSETS) {
  const stemmed = set.map((w) => stemKey(w));
  const all = [...new Set([...set, ...stemmed])];
  for (const w of all) {
    const existing = INDEX.get(w);
    if (existing) {
      for (const x of all) {
        if (!existing.includes(x)) existing.push(x);
      }
    } else {
      INDEX.set(w, [...all]);
    }
  }
}

export function expandTokens(tokens: string[]): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  for (const t of tokens) {
    if (!seen.has(t)) {
      seen.add(t);
      out.push(t);
    }
    const syn = INDEX.get(t);
    if (!syn) continue;
    for (const s of syn) {
      if (seen.has(s)) continue;
      seen.add(s);
      out.push(s);
    }
  }
  return out;
}

export function isExpandedToken(original: Set<string>, token: string): boolean {
  return !original.has(token);
}
