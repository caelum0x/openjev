/** The threshold set for answers produced by `engine`. */
export function thresholdsFor(engine: SystemOneEngine | null | undefined): ThresholdSet {
  if (engine?.kind === "embedding") {
    return { id: "embedding", fitted_on: EMBEDDING_THRESHOLDS_FITTED_ON, values: EMBEDDING_THRESHOLDS };
  }
  return { id: "default", fitted_on: null, values: DEFAULT_THRESHOLDS };
}

/** What a cookbook response reports about the gates it applied. */
export function thresholdInfo<K extends keyof CookbookThresholds>(set: ThresholdSet, key: K) {
  return { set: set.id, fitted_on: set.fitted_on, values: set.values[key] };
}
