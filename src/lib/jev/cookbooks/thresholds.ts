/**
 * Decision thresholds the cookbooks apply to System One answers, per engine.
 *
 * A threshold on a noul or a confidence is a statement about ONE engine's score
 * distribution: the sentence-embedding engine and the lexical (TF-IDF) engine
 * put the same inputs at very different probabilities. So each cookbook reads
 * its gates from the set that matches the engine that actually answered.
 *
 *  - `DEFAULT_THRESHOLDS`: the original hand-set values. Used for the lexical
 *    engine and for every backend that is not the embedding engine (neural
 *    sidecars, cloud, LLM), where nothing has been re-measured.
 *  - `EMBEDDING_THRESHOLDS`: chosen by `scripts/cookbook-thresholds.ts` on the
 *    embedding engine, on the TUNE half of the labelled cookbook sets in
 *    ./tuning-sets.ts, and reported on the held-out half it never saw. See
 *    docs/COOKBOOK-THRESHOLDS.md for the numbers and the selection rule.
 *
 * Client-safe (no server imports).
 */
import type { SystemOneEngine } from "../types.ts";

export type SmarthomeGates = {
  /** Minimum `allow` noul to execute a reversible command. */
  allow: number;
  /** Minimum `allow` noul to execute an irreversible one (unlock, disarm). */
  allow_irreversible: number;
  /** Minimum joint choice confidence (category/domain/device/action) to execute. */
  confidence: number;
  confidence_irreversible: number;
  /** Minimum `compound` noul (with >= 2 split parts) to split the utterance. */
  compound: number;
  /** Minimum `is_query` noul to treat the utterance as a status query. */
  is_query: number;
  /** Minimum `whole_home` noul to target every room. */
  whole_home: number;
};

export type CascadeGates = {
  /** A field fires (escalate to the reasoner) when P(wrong) is above this. */
  fire: number;
};

export type ConsistencyGates = {
  /** Deny when `deny` is above this (and above `pay`). */
  deny_min: number;
  /** Pay when `pay` is above this ... */
  pay_min: number;
  /** ... and `deny` is below this ... */
  pay_max_deny: number;
  /** ... and `human_review` is below this. Otherwise: human review. */
  pay_max_human: number;
};

export type CookbookThresholds = {
  smarthome: SmarthomeGates;
  cascade: CascadeGates;
  consistency: ConsistencyGates;
};

export type ThresholdSetId = "embedding" | "default";

export type ThresholdSet = {
  id: ThresholdSetId;
  /** Engine version the set was fitted on (null for the hand-set defaults). */
  fitted_on: string | null;
  values: CookbookThresholds;
};

export const DEFAULT_THRESHOLDS: CookbookThresholds = {
  smarthome: {
    allow: 0.5,
    allow_irreversible: 0.85,
    confidence: 0.35,
    confidence_irreversible: 0.55,
    compound: 0.55,
    is_query: 0.7,
    whole_home: 0.7,
  },
  cascade: { fire: 0.7 },
  consistency: { deny_min: 0.7, pay_min: 0.65, pay_max_deny: 0.4, pay_max_human: 0.75 },
};

/**
 * Tuned on the embedding engine (gte-small int8). Regenerate with
 * `node --experimental-strip-types scripts/cookbook-thresholds.ts --write`.
 */
// BEGIN EMBEDDING_THRESHOLDS (generated by scripts/cookbook-thresholds.ts)
export const EMBEDDING_THRESHOLDS_FITTED_ON = "gte-small+pfa4be686";
export const EMBEDDING_THRESHOLDS: CookbookThresholds = {
  smarthome: {
    allow: 0.35,
    allow_irreversible: 0.85,
    confidence: 0.35,
    confidence_irreversible: 0.55,
    compound: 0.55,
    is_query: 0.7,
    whole_home: 0.7,
  },
  cascade: { fire: 0.38 },
  consistency: {
    deny_min: 0.7,
    pay_min: 0.85,
    pay_max_deny: 0.4,
    pay_max_human: 0.75,
  },
};
